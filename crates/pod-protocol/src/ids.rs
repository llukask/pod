//! Entity ids (spec section 1).
//!
//! Every id is a UUID that travels as a lowercase hyphenated string. Each
//! entity gets its own newtype so a podcast id can't be passed where an
//! episode id is expected.

use std::fmt;
use std::str::FromStr;

use serde::{Deserialize, Serialize};
use uuid::Uuid;

use crate::feed_url::NormalizedFeedUrl;

/// Declares a `Copy` newtype over [`Uuid`] with string serde, `Display` and
/// `FromStr`.
///
/// `Uuid`'s own serde impl writes the lowercase hyphenated form for
/// human-readable formats such as JSON, which is the only wire format.
/// Parsing accepts every form `Uuid::parse_str` does (braced, simple, URN,
/// any case); the id prints back in canonical form.
macro_rules! uuid_newtype {
    ($(#[$meta:meta])* $name:ident) => {
        $(#[$meta])*
        #[derive(
            Debug,
            Clone,
            Copy,
            PartialEq,
            Eq,
            PartialOrd,
            Ord,
            Hash,
            Serialize,
            Deserialize,
            utoipa::ToSchema,
        )]
        #[serde(transparent)]
        pub struct $name(Uuid);

        impl $name {
            /// Wraps a UUID read from storage or another trusted source.
            pub const fn from_uuid(uuid: Uuid) -> Self {
                Self(uuid)
            }

            /// The underlying UUID.
            pub const fn as_uuid(&self) -> Uuid {
                self.0
            }
        }

        impl fmt::Display for $name {
            fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
                fmt::Display::fmt(&self.0.hyphenated(), f)
            }
        }

        impl FromStr for $name {
            type Err = uuid::Error;

            fn from_str(s: &str) -> Result<Self, Self::Err> {
                Uuid::parse_str(s).map(Self)
            }
        }
    };
}

uuid_newtype! {
    /// A podcast, UUIDv5 of its normalized feed URL.
    PodcastId
}

uuid_newtype! {
    /// An episode, UUIDv5 of its podcast id and episode key.
    EpisodeId
}

uuid_newtype! {
    /// A user account, UUIDv7 generated by the server at registration.
    UserId
}

uuid_newtype! {
    /// A logged-in device session, UUIDv7 generated by the server at login.
    DeviceId
}

uuid_newtype! {
    /// A client mutation, UUIDv7 generated by the client that made it.
    MutationId
}

impl PodcastId {
    /// `NS_PODCAST` from the spec.
    pub const NAMESPACE: Uuid = uuid::uuid!("6f1d3c2a-9b0e-5e7a-8c41-2d7f0a3b9e01");

    /// The id of the podcast at `url`.
    pub fn from_feed_url(url: &NormalizedFeedUrl) -> Self {
        Self(Uuid::new_v5(&Self::NAMESPACE, url.normalized().as_bytes()))
    }
}

impl EpisodeId {
    /// `NS_EPISODE` from the spec.
    pub const NAMESPACE: Uuid = uuid::uuid!("0c8a7e54-3f21-5b6d-9a10-7e4c2b1d8f02");

    /// The id of the episode with `key` (see [`episode_key`]) in `podcast_id`.
    pub fn new(podcast_id: PodcastId, key: &str) -> Self {
        let name = format!("{podcast_id}\n{key}");
        Self(Uuid::new_v5(&Self::NAMESPACE, name.as_bytes()))
    }
}

impl UserId {
    /// A fresh time-ordered id.
    pub fn new_v7() -> Self {
        Self(Uuid::now_v7())
    }
}

impl DeviceId {
    /// A fresh time-ordered id.
    pub fn new_v7() -> Self {
        Self(Uuid::now_v7())
    }
}

impl MutationId {
    /// A fresh time-ordered id.
    pub fn new_v7() -> Self {
        Self(Uuid::now_v7())
    }
}

/// The key an episode id is derived from: the item's `<guid>` (or Atom
/// `<id>`) trimmed, or the enclosure URL when the guid is missing or blank.
///
/// The enclosure URL is used as written; the spec only trims the guid.
pub fn episode_key<'a>(guid: Option<&'a str>, enclosure_url: &'a str) -> &'a str {
    match guid.map(str::trim) {
        Some(guid) if !guid.is_empty() => guid,
        _ => enclosure_url,
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    const PODCAST: &str = "72093705-dcd7-553f-9f92-c7c280d2f56b";

    #[test]
    fn ids_serialize_as_lowercase_hyphenated_strings() {
        let id = PodcastId::from_uuid(Uuid::parse_str(PODCAST).expect("literal is a UUID"));
        let json = serde_json::to_string(&id).expect("ids serialize");
        assert_eq!(json, format!("\"{PODCAST}\""));
        assert_eq!(
            serde_json::from_str::<PodcastId>(&json).expect("ids deserialize"),
            id
        );
    }

    #[test]
    fn display_is_canonical_whatever_form_was_parsed() {
        let id: EpisodeId = PODCAST
            .to_uppercase()
            .replace('-', "")
            .parse()
            .expect("simple uppercase form parses");
        assert_eq!(id.to_string(), PODCAST);
    }

    #[test]
    fn generated_ids_are_v7() {
        assert_eq!(UserId::new_v7().as_uuid().get_version_num(), 7);
        assert_eq!(DeviceId::new_v7().as_uuid().get_version_num(), 7);
        assert_eq!(MutationId::new_v7().as_uuid().get_version_num(), 7);
    }

    #[test]
    fn invalid_id_strings_are_rejected() {
        assert!("not-a-uuid".parse::<MutationId>().is_err());
    }
}
